/* --------------------------- Defensive list helpers ------------------------ */
const asArray = (v) => (Array.isArray(v) ? v : []);

// Normalizes whatever /api/products/filter-options returned into the exact
// shape the UI expects, so a malformed payload can never crash the dropdowns.
function normalizeFilterOptions(d) {
  d = (d && typeof d === 'object') ? d : {};
  return {
    brands: asArray(d.brands),
    ram: asArray(d.ram),
    rom: asArray(d.rom),
    colors: asArray(d.colors),
    priceMin: Number.isFinite(d.priceMin) ? d.priceMin : 0,
    priceMax: Number.isFinite(d.priceMax) ? d.priceMax : 60000000
  };
}

// Safely extracts the catalog list from any /api/products response shape:
// { products: [...] } | { data: [...] } | [...] | anything else -> []
function extractProductList(payload) {
  if (Array.isArray(payload)) return payload;
  if (payload && typeof payload === 'object') {
    if (Array.isArray(payload.products)) return payload.products;
    if (Array.isArray(payload.data)) return payload.data;
  }
  return [];
}


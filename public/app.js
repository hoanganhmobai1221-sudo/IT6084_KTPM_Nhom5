// Validates the coupon against the server and updates the live discount.
async function applyCoupon() {
  const code = inputVal('input-coupon');
  const totals = computeTotals();
  if (!code) {
    State.couponMsg = { type: 'error', text: 'Vui lòng nhập mã giảm giá trước khi áp dụng.', testid: 'coupon-error-msg' };
    State.coupon = null;
    render();
    return;
  }
  const r = await api('GET', `/api/coupons/validate?code=${encodeURIComponent(code)}&subtotal=${totals.subtotal}`);
  const d = r.data || {};
  if (r.ok && d.valid) {
    State.coupon = { code: d.code, type: d.type, value: d.value };
    State.couponMsg = { type: 'success', text: `${d.message} — bạn tiết kiệm được ${fmtVND(d.discount)}.`, testid: 'coupon-success-msg' };
  } else {
    State.coupon = null;
    State.couponMsg = { type: 'error', text: d.message || 'Mã giảm giá không hợp lệ.', testid: 'coupon-error-msg' };
  }
  render();
}

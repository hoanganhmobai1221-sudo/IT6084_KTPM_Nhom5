async function saveProductForm() {
  const err = byId('admin-form-error-msg');
  if (err) err.className = 'hidden';
  const name = inputVal('input-product-name');
  const brand = inputVal('select-product-brand');
  const description = inputVal('textarea-product-description');
  const specs = inputVal('textarea-product-specs');
  const active = byId('checkbox-product-active') ? byId('checkbox-product-active').checked : true;

  if (!name || !brand) {
    if (err) { err.className = ''; err.textContent = 'Vui lòng nhập tên sản phẩm và chọn thương hiệu.'; }
    return;
  }

  const variants = State.adminForm.variants.map((v, idx) => ({
    color: inputVal('input-variant-color-' + idx),
    ram: Number(inputVal('input-variant-ram-' + idx)),
    rom: Number(inputVal('input-variant-rom-' + idx)),
    price: Number(inputVal('input-variant-price-' + idx)),
    stock: Number(inputVal('input-variant-stock-' + idx))
  }));

  const payload = { name, brand, description, specs, active, variants };
  const isEdit = !!State.adminForm.editingId;
  const url = isEdit ? '/api/admin/products/' + State.adminForm.editingId : '/api/admin/products';
  const r = await api(isEdit ? 'PUT' : 'POST', url, payload);

  if (!r.ok) {
    if (err) { err.className = ''; err.textContent = r.data.message || 'Không thể lưu thông tin sản phẩm.'; }
    return;
  }
  closeAdminProductForm();
  await Promise.all([refreshAdminProducts(), refreshProducts(), refreshFilterOptions()]);
  setAdminTab('products');
  toast(isEdit ? 'Cập nhật sản phẩm thành công.' : 'Tạo mới sản phẩm thành công.', 'success');
}


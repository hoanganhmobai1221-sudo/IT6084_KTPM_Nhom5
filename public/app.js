// --- Dual range price slider -------------------------------------------------
// The range thumbs stay in sync with the numeric inputs (the canonical filter
// values read by applyFilters()), so both dragging and typing work.
function onPriceRangeInput(which) {
  const minEl = byId('range-min-price');
  const maxEl = byId('range-max-price');
  if (!minEl || !maxEl) return;
  let lo = Number(minEl.value);
  let hi = Number(maxEl.value);
  if (lo > hi) {
    if (which === 'min') { lo = hi; minEl.value = String(lo); }
    else { hi = lo; maxEl.value = String(hi); }
  }
  const numMin = byId('input-min-price');
  const numMax = byId('input-max-price');
  if (numMin) numMin.value = String(lo);
  if (numMax) numMax.value = String(hi);
  updatePriceRangeUI();
}

function updatePriceRangeUI() {
  const minEl = byId('range-min-price');
  const maxEl = byId('range-max-price');
  if (!minEl || !maxEl) return;
  const lo = Number(minEl.value);
  const hi = Number(maxEl.value);
  const lo0 = Number(minEl.min);
  const hi0 = Number(minEl.max);
  const span = (hi0 - lo0) || 1;
  const pct = (v) => Math.min(100, Math.max(0, ((v - lo0) / span) * 100));
  const label = byId('price-range-label');
  const fill = byId('price-range-fill');
  if (label) label.textContent = `${fmtVND(lo)} – ${fmtVND(hi)}`;
  if (fill) { fill.style.left = pct(lo) + '%'; fill.style.right = (100 - pct(hi)) + '%'; }
}


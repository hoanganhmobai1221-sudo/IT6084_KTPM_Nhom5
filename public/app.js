function onVariantChange() {
  const sel = byId('select-variant');
  const note = byId('modal-stock-note');
  const btn = byId('btn-add-variant');
  const qty = byId('input-qty');
  const err = byId('modal-error-msg');
  if (!sel || !note || !btn || !qty) return;
  const v = State.productDetail.variants.find((x) => x.id === sel.value);
  if (!v) return;
  note.innerHTML = `<span class="text-slate-500 text-xs font-normal">Giá:</span> <span class="text-base font-extrabold text-blue-700">${fmtVND(v.price)}</span> · <span class="${v.stock > 0 ? 'text-emerald-600' : 'text-rose-600'} font-bold">Còn ${v.stock} máy</span>`;
  qty.max = String(v.stock);
  qty.min = '1';
  btn.disabled = v.stock < 1;
  if (err) err.className = 'hidden';
}

function addFromModal() {
  const sel = byId('select-variant');
  const qty = byId('input-qty');
  const err = byId('modal-error-msg');
  const q = qty ? parseInt(qty.value, 10) : 1;
  if (!q || q < 1) {
    if (err) { err.className = ''; err.textContent = 'Số lượng đặt mua phải từ 1 trở lên.'; }
    return;
  }
  if (addToCart(sel.value, q)) {
    closeDetails();
    toast('Đã thêm sản phẩm vào giỏ hàng thành công.', 'success');
  } else {
    const e = byId('modal-error-msg');
    if (e) { e.className = ''; e.textContent = State.cartMsg.text || 'Không thể thêm số lượng này.'; }
  }
}

function quickAdd(productId) {
  const p = asArray(State.products).find((x) => x.id === productId);
  if (!p) return;
  const sorted = asArray(p.variants).slice().sort((a, b) => a.price - b.price);
  const v = sorted.find((x) => x.stock > 0);
  if (!v) { toast(`${p.name} hiện đang tạm hết hàng.`, 'error'); return; }
  if (addToCart(v.id, 1)) toast(`Đã thêm ${p.name} (${v.color}) vào giỏ hàng.`, 'success');
}

// MANDATORY BUSINESS CONSTRAINT: the client may never raise the cart quantity
// beyond the current available stock. The order endpoint re-validates every
// quantity server-side as the authoritative source of truth.
function addToCart(variantId, qty) {
  const v = findVariantLocal(variantId);
  if (!v) {
    State.cartMsg = { type: 'error', text: 'Phiên bản này hiện không còn khả dụng. Vui lòng tải lại trang.', testid: 'cart-error-msg' };
    if (State.view === 'cart') render();
    return false;
  }
  const existing = State.cart.find((i) => i.variantId === variantId);
  const current = existing ? existing.qty : 0;
  const next = current + qty;
  if (next > v.stock) {
    State.cartMsg = {
      type: 'error',
      text: `Không thể thêm quá số lượng trong kho: chỉ còn ${v.stock} máy "${v.productName}" (${v.color} ${v.ram}GB/${v.rom}GB)${current ? `, bạn đã có ${current} máy trong giỏ` : ''}.`,
      testid: 'cart-error-msg'
    };
    if (State.view === 'cart') render();
    return false;
  }
  if (existing) existing.qty = next;
  else State.cart.push({ variantId, qty });
  saveCart();
  State.coupon = null;
  State.cartMsg = { type: 'success', text: `Đã thêm ${qty} × "${v.productName}" (${v.color} ${v.ram}GB/${v.rom}GB) vào giỏ hàng.`, testid: 'cart-success-msg' };
  return true;
}

function setCartMsg(type, text) {
  State.cartMsg = { type, text, testid: type === 'success' ? 'cart-success-msg' : 'cart-error-msg' };
}
/* ----------------------------- Cart view ---------------------------------- */
// Real-time totals: Subtotal − Discount = Grand Total
function computeTotals() {
  let subtotal = 0;
  for (const it of State.cart) {
    const v = findVariantLocal(it.variantId);
    if (v) subtotal += v.price * it.qty;
  }
  let discount = 0;
  if (State.coupon) {
    discount = State.coupon.type === 'percent'
      ? Math.round(subtotal * State.coupon.value / 100)
      : Math.min(State.coupon.value, subtotal);
  }
  return { subtotal, discount, grandTotal: Math.max(0, subtotal - discount) };
}


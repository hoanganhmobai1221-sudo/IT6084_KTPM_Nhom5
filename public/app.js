async function refreshProducts() {
  const p = new URLSearchParams();
  const f = State.filters;
  if (f.search) p.set('search', f.search);
  if (f.brand && f.brand !== 'all') p.set('brand', f.brand);
  if (f.ram !== '' && f.ram !== 'all') p.set('ram', f.ram);
  if (f.rom !== '' && f.rom !== 'all') p.set('rom', f.rom);
  if (f.minPrice !== '') p.set('minPrice', f.minPrice);
  if (f.maxPrice !== '') p.set('maxPrice', f.maxPrice);
  p.set('sort', f.sort);
  State.productsLoading = true;
  try {
    const r = await api('GET', '/api/products?' + p.toString());
    // Safe extraction handles every response shape: { products } | { data } | [..] | undefined
    State.products = r.ok ? extractProductList(r.data) : [];
  } finally {
    State.productsLoading = false;
  }
  return State.products;
}


  const stockNote = cheapest && cheapest.stock > 0
    ? `Còn ${cheapest.stock} máy (${cheapest.color})`
    : 'Hết hàng tạm thời';
  const stockCls = cheapest && cheapest.stock > 0 ? 'text-emerald-600 font-semibold' : 'text-rose-500 font-semibold';


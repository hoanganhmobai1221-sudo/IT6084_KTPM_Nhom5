async function submitOrder() {
  const err = byId('order-error-msg');
  if (err) err.className = 'hidden';
  if (!State.user) {
    if (err) { err.className = ''; err.textContent = 'Vui lòng đăng nhập trước khi đặt hàng.'; }
    return;
  }
  const fullName = inputVal('input-checkout-fullname');
  const phone = inputVal('input-checkout-phone');
  const address = inputVal('input-checkout-address');
  const paymentMethod = inputVal('select-payment');
  const items = State.cart.map((i) => ({ variantId: i.variantId, qty: i.qty }));

  if (!State.cart.length) {
    if (err) { err.className = ''; err.textContent = 'Giỏ hàng của bạn đang trống. Vui lòng chọn ít nhất một sản phẩm trước khi thanh toán.'; }
    return;
  }

  const r = await api('POST', '/api/orders', {
    fullName, phone, address, paymentMethod,
    items,
    couponCode: State.coupon ? State.coupon.code : ''
  });

  if (!r.ok) {
    if (err) { err.className = ''; err.textContent = r.data.message || 'Không thể tạo đơn hàng. Vui lòng thử lại.'; }
    return;
  }

  State.lastOrder = r.data.order;
  State.cart = [];
  State.coupon = null;
  saveCart();
  openOrders();
  toast(`Đặt hàng thành công! Mã đơn: ${r.data.order.id}`, 'success');
}
